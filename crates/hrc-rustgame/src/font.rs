fn rect(out: &mut Vec<HudVertex>, x0: f32, y0: f32, x1: f32, y1: f32, screen: (u32, u32), color: [f32; 4]) {
    let (w, h) = (screen.0 as f32, screen.1 as f32);
    let px = |x: f32| x / w * 2.0 - 1.0;
    let py = |y: f32| 1.0 - y / h * 2.0;
    let v = |x: f32, y: f32| HudVertex { pos: [px(x), py(y)], color };
    out.extend_from_slice(&[v(x0, y0), v(x1, y0), v(x1, y1), v(x0, y0), v(x1, y1), v(x0, y1)]);
}

pub const SCALE: f32 = 3.0;
pub const ADVANCE: f32 = 6.0 * SCALE;
pub const LINE_H: f32 = 7.0 * SCALE + 6.0;

/// يبني رؤوس HUD: خلفية شفافة داكنة + نص أبيض. الإحداثيات بالبكسل من أعلى اليسار.
pub fn build_hud(lines: &[String], screen: (u32, u32)) -> Vec<HudVertex> {
    let mut out = Vec::new();
    let widest = lines.iter().map(|l| l.chars().count()).max().unwrap_or(0) as f32;
    let (x, y) = (10.0, 10.0);
    rect(&mut out, x - 6.0, y - 6.0, x + widest * ADVANCE + 6.0, y + lines.len() as f32 * LINE_H + 2.0, screen, [0.0, 0.0, 0.0, 0.45]);
    for (li, line) in lines.iter().enumerate() {
        let ty = y + li as f32 * LINE_H;
        for (ci, ch) in line.chars().enumerate() {
            let tx = x + ci as f32 * ADVANCE;
            for (row, bits) in glyph(ch).iter().enumerate() {
                for col in 0..5 {
                    if bits & (0x10 >> col) != 0 {
                        let (px0, py0) = (tx + col as f32 * SCALE, ty + row as f32 * SCALE);
                        rect(&mut out, px0, py0, px0 + SCALE, py0 + SCALE, screen, [1.0, 1.0, 1.0, 1.0]);
                    }
                }
            }
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_hud_char_has_a_glyph() {
        for c in "HORIZON RUST 0.1 (EXPERIMENTAL) FPS XYZ: -123456789, CHUNKS FACES PLAYER BACKEND /".chars() {
            if c != ' ' {
                assert_ne!(glyph(c), glyph('\u{1}'), "{c} falls back to the unknown box");
                assert_ne!(glyph(c), [0; 7], "{c} is blank");
            }
        }
        assert_eq!(glyph('a'), glyph('A'));
        assert_eq!(glyph(' '), [0; 7]);
    }

    #[test]
    fn hud_vertices_come_in_triangles_and_stay_on_screen() {
        let v = build_hud(&["FPS 60".to_string(), "XYZ 1 2 3".to_string()], (1280, 720));
        assert!(!v.is_empty() && v.len() % 6 == 0);
        assert!(v.iter().all(|p| p.pos[0] >= -1.0 && p.pos[0] <= 1.0 && p.pos[1] >= -1.0 && p.pos[1] <= 1.0));
    }

    #[test]
    fn letter_i_draws_expected_pixels() {
        // خلفية (6 رؤوس) + عدد وحدات البكسل المضاءة في "I" (3+1+1+1+1+1+3 = 11) × 6 رؤوس
        assert_eq!(build_hud(&["I".to_string()], (800, 600)).len(), 6 + 11 * 6);
    }

    #[test]
    fn empty_input_is_safe() {
        assert_eq!(build_hud(&[], (800, 600)).len(), 6);
    }
}
